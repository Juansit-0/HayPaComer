CREATE TABLE locales (
    code TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    is_default BOOLEAN NOT NULL DEFAULT false
);

CREATE UNIQUE INDEX locales_one_default ON locales (is_default) WHERE is_default;

INSERT INTO locales (code, name, is_default) VALUES
    ('es-CO', 'Español', true),
    ('en', 'English', false);

ALTER TABLE users ADD COLUMN locale TEXT REFERENCES locales (code);

CREATE TABLE translations (
    locale TEXT NOT NULL REFERENCES locales (code) ON DELETE CASCADE,
    key TEXT NOT NULL,
    text TEXT NOT NULL CHECK (length(trim(text)) > 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (locale, key)
);

CREATE TABLE message_templates (
    locale TEXT NOT NULL REFERENCES locales (code) ON DELETE CASCADE,
    source TEXT NOT NULL,
    target TEXT NOT NULL CHECK (length(trim(target)) > 0),
    PRIMARY KEY (locale, source)
);

